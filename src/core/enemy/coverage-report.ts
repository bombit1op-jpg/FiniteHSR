import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { enemyCoverage, enemyCoverageSummary, type EnemyCoverageRow } from './coverage'

/** §64 — regenerate `docs/enemies/implementation-matrix.md` from the catalog + the authored
 *  behavior registry. Run: `npx tsx src/core/enemy/coverage-report.ts`.
 *
 *  The matrix is the roster's source of truth for "what is done": every base name is listed with
 *  its rank, variant/record count and behaviour status. Unimplemented entries carry the annotated
 *  mechanic categories (navigation aid from `enemies_annotated_ru.json`) so the next batch is
 *  obvious — never a hand-authored list that drifts from the engine. */

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..', '..')
const OUT = join(ROOT, 'docs', 'enemies', 'implementation-matrix.md')

interface Annotated {
  baseName: string
  mechanicsRu?: string[]
}

function reasonsByBase(): Map<string, string[]> {
  const out = new Map<string, string[]>()
  try {
    const raw = JSON.parse(readFileSync(join(ROOT, 'hsr-data', 'enemies_annotated_ru.json'), 'utf8')) as Annotated[]
    for (const r of raw) {
      const prev = out.get(r.baseName) ?? []
      for (const m of r.mechanicsRu ?? []) if (!prev.includes(m)) prev.push(m)
      out.set(r.baseName, prev)
    }
  } catch {
    // annotations are a navigation aid only; the matrix still generates without them
  }
  return out
}

function row(r: EnemyCoverageRow, reasons: Map<string, string[]>): string {
  const modes = r.modes.filter(m => m !== '').join(', ') || '—'
  const status = r.behavioral ? '`implemented`' : '`data-verified` / not implemented (default attack)'
  const note = r.behavioral ? (r.key ?? '') : (reasons.get(r.baseName)?.join('; ') || '—')
  return `| ${r.baseName} | ${r.rank} | ${r.variants} | ${modes} | ${status} | ${note} |`
}

function section(title: string, rows: EnemyCoverageRow[], reasons: Map<string, string[]>): string {
  const head = `| Enemy | Rank | Records | Non-base modes | Status | Mechanics / key |\n|---|---|---|---|---|---|`
  return [`### ${title}`, '', head, ...rows.map(r => row(r, reasons)), ''].join('\n')
}

function main(): void {
  const rows = enemyCoverage()
  const sum = enemyCoverageSummary()
  const reasons = reasonsByBase()
  const byRank = (rank: string) => rows.filter(r => r.rank === rank)
  const gaps = rows.filter(r => !r.behavioral).length

  const doc = [
    '# Enemy Implementation Matrix',
    '',
    '> Generated by `npx tsx src/core/enemy/coverage-report.ts` — do not edit by hand.',
    '',
    'Source of truth: `hsr-data/enemies.json` (via `src/core/enemy/parse.ts`). An authored',
    '`EnemyBehavior` in `src/core/enemy/profiles.ts` is keyed by the enemy base name (the exact',
    'endgame card name for the launched unit). `Status` values:',
    '',
    '- `implemented` — an authored behaviour resolves for this enemy (abilities, AI, phases/passive).',
    '- `data-verified / not implemented` — the catalog entry parses and its config resolves, but the',
    '  unit falls back to the engine default attack; the `Mechanics` column lists the annotated',
    '  mechanic categories still to build.',
    '',
    'Certificate rule: `implemented` ≠ `tested`. A row only reaches behavioural regression coverage',
    'once `tests/golden/enemies/` pins its abilities/state, not merely because it is registered.',
    '',
    '## Summary',
    '',
    `- Base names: **${sum.bases}** — records: **${sum.records}**`,
    `- Implemented: **${sum.behavioral}** / ${sum.bases} base names`,
    `- Not implemented: **${gaps}**`,
    `- mob: ${sum.byRank.mob.bases} bases (${sum.byRank.mob.behavioral} implemented)`,
    `- elite: ${sum.byRank.elite.bases} bases (${sum.byRank.elite.behavioral} implemented)`,
    `- boss: ${sum.byRank.boss.bases} bases (${sum.byRank.boss.behavioral} implemented)`,
    '',
    section('Boss', byRank('boss'), reasons),
    section('Elite', byRank('elite'), reasons),
    section('Mob', byRank('mob'), reasons),
  ].join('\n')

  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, doc, 'utf8')
  console.log(`wrote ${OUT} (${rows.length} rows)`)
}

main()
