import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { enemyAbilityInventory, enemyInventorySummary, type EnemyAbilityRow } from './inventory'
import { BOSS_BEHAVIORS } from './profiles'
import { MOB_BEHAVIORS } from './mob-profiles'
import type { EnemyEffect } from './ability'

/** §85.E1 — regenerate the per-ability verification inventory + report.
 *
 *  Run: `npx tsx src/core/enemy/inventory-report.ts`
 *
 *  Writes `docs/enemies/verification-inventory.json` (machine-readable registry) and
 *  `docs/enemies/verification-inventory.md` (human coverage report). Distinct from the §64
 *  `implementation-matrix.md`: that answers "is the enemy authored" (base name), this answers "is
 *  each declared *ability* linked to a test" (per ability). Test linkage is a heuristic string scan
 *  of `tests/` — EVIDENCE-IN, not proof: `unlinked` rows are candidates for E3, and a `linked` row
 *  still needs its assertions audited. Nothing here weakens or replaces a real test. */

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..', '..')
const TESTS = join(ROOT, 'tests')
const OUT_JSON = join(ROOT, 'docs', 'enemies', 'verification-inventory.json')
const OUT_MD = join(ROOT, 'docs', 'enemies', 'verification-inventory.md')

function walk(d: string, acc: string[] = []): string[] {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, e.name)
    if (e.isDirectory()) walk(p, acc)
    else if (e.name.endsWith('.ts')) acc.push(p)
  }
  return acc
}

/** buff/debuff/dot/self-clear ids declared inside an ability's effects (strong linkage tokens) */
function effectIds(effects: EnemyEffect[], out: string[] = []): string[] {
  for (const e of effects) {
    if (e.op === 'buff' || e.op === 'debuff') out.push(e.buff.id)
    else if (e.op === 'dot') out.push(e.kind)
    else if (e.op === 'dispelSelf') out.push(e.id)
    else if (e.op === 'oneOf') effectIds(e.effects, out)
  }
  return out
}

type Link = 'linked' | 'enemy-only' | 'none'
interface Row extends EnemyAbilityRow { link: Link; signals: string[] }

const slug = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'x'

/** ability row id -> declared effect payload ids, read straight from the authored behaviours */
function effectIdIndex(): Map<string, string[]> {
  const idx = new Map<string, string[]>()
  for (const [name, b] of [...Object.entries(BOSS_BEHAVIORS), ...Object.entries(MOB_BEHAVIORS)])
    for (const a of b.abilities) idx.set(`enemy/${slug(name)}/${a.id}`, effectIds(a.effects))
  return idx
}

function main(): void {
  const base = enemyAbilityInventory()
  const summary = enemyInventorySummary(base)
  const corpus = walk(TESTS).map(f => readFileSync(f, 'utf8')).join('\n')
  const fxByAbility = effectIdIndex()

  const rows: Row[] = base.map(r => {
    const idHit = corpus.includes(`'${r.abilityId}'`) || corpus.includes(`"${r.abilityId}"`) || corpus.includes(`\`${r.abilityId}\``)
    const nameHit = corpus.includes(r.abilityName)
    const fxHit = (fxByAbility.get(r.id) ?? []).some(id => corpus.includes(id))
    const enemyHit = corpus.includes(r.enemy)
    const signals: string[] = []
    if (idHit) signals.push('ability-id')
    if (nameHit) signals.push('ability-name')
    if (fxHit) signals.push('effect-id')
    if (enemyHit) signals.push('enemy-name')
    const link: Link = (idHit || nameHit || fxHit) ? 'linked' : enemyHit ? 'enemy-only' : 'none'
    return { ...r, link, signals }
  })

  const linked = rows.filter(r => r.link === 'linked').length
  const enemyOnly = rows.filter(r => r.link === 'enemy-only').length
  const none = rows.filter(r => r.link === 'none').length

  mkdirSync(dirname(OUT_JSON), { recursive: true })
  writeFileSync(OUT_JSON, JSON.stringify({
    generatedFrom: 'src/core/enemy/{profiles,mob-profiles}.ts',
    note: 'test linkage is a heuristic string scan of tests/ (evidence-in, not proof); unlinked rows are E3 candidates',
    totals: { ...summary, linked, enemyOnly, none },
    abilities: rows,
  }, null, 1))

  const gap = rows.filter(r => r.link !== 'linked')
  const md = [
    '# Enemy Ability Verification Inventory',
    '',
    '> Generated by `npx tsx src/core/enemy/inventory-report.ts` — do not edit by hand.',
    '',
    'Per-ability expansion of the authored enemy registry. Complements §64',
    '`implementation-matrix.md` (which is per base *name*): this is one row per declared *ability*.',
    '',
    '**Test linkage is a heuristic scan of `tests/`** (`ability-id` / `ability-name` / `effect-id` /',
    '`enemy-name`). `linked` = an ability id, exact name, or a declared effect payload id appears in',
    'the corpus; `enemy-only` = only the enemy name appears; `none` = no reference. `linked` is',
    'EVIDENCE-IN, not proof of assertion quality — every row still needs an assertion audit (E3).',
    '',
    '## Totals',
    '',
    `- Enemies: **${summary.enemies}** — abilities: **${summary.abilities}** — enumerated requirements: **${summary.requirements}**`,
    `- by rank: mob ${summary.byRank.mob} · elite ${summary.byRank.elite} · boss ${summary.byRank.boss}`,
    `- telegraphed (cast>0): ${summary.telegraphed} · with cooldown: ${summary.withCooldown} · with charges: ${summary.withCharges} · state-gated: ${summary.withRequire}`,
    `- behaviours with §56 phases: ${summary.phasedBehaviors} · with §57 passive: ${summary.passiveBehaviors}`,
    `- linkage: **linked ${linked}** · enemy-only ${enemyOnly} · none ${none} (of ${summary.abilities})`,
    '',
    '## Effect-op histogram (abilities declaring each op)',
    '',
    '| op | abilities |',
    '|---|---|',
    ...Object.entries(summary.ops).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## Verification-dimension totals (requirements per dimension)',
    '',
    '| dimension | requirements |',
    '|---|---|',
    ...Object.entries(summary.dimensions).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    `## Abilities without a strong test signal (${gap.length})`,
    '',
    '| enemy | ability id | ability | ops | dimensions | link | signals |',
    '|---|---|---|---|---|---|---|',
    ...gap.map(r => `| ${r.enemy} | ${r.abilityId} | ${r.abilityName} | ${r.ops.join(',')} | ${r.dimensions.join(',')} | ${r.link} | ${r.signals.join(',')} |`),
    '',
  ].join('\n')
  writeFileSync(OUT_MD, md)

  console.log(`wrote ${OUT_JSON}`)
  console.log(`wrote ${OUT_MD}`)
  console.log(`enemies ${summary.enemies} · abilities ${summary.abilities} · requirements ${summary.requirements}`)
  console.log(`linkage: linked ${linked} · enemy-only ${enemyOnly} · none ${none}`)
}

main()
