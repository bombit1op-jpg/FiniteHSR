export default () => {
  const rows = enemyCoverage()
  const sum = enemyCoverageSummary()
  const records = DEFINITIONS.reduce((n, d) => n + d.variants.length, 0)

  const impl = implementedEnemyNames().sort()

  const cases = [
    t.eq('64 coverage: one row per catalog definition', rows.length, DEFINITIONS.length),
    raw('64 coverage: every base name appears once', new Set(rows.map(r => r.baseName)).size === rows.length, `${rows.length} rows`),
    t.eq('64 coverage: record total matches the raw catalog', sum.records, records),
    raw('64 coverage: 250 base names over 379 records', sum.bases === 250 && sum.records === 379, `bases=${sum.bases} records=${sum.records}`),
    raw('64 coverage: rank split is mob/elite/boss = 133/55/62',
      sum.byRank.mob.bases === 133 && sum.byRank.elite.bases === 55 && sum.byRank.boss.bases === 62,
      `mob=${sum.byRank.mob.bases} elite=${sum.byRank.elite.bases} boss=${sum.byRank.boss.bases}`),
    t.eq('64 coverage: implemented set is exactly the authored profiles', impl, [...IMPLEMENTED].sort()),
    raw('64 coverage: implemented count is summarized per rank',
      sum.byRank.mob.behavioral + sum.byRank.elite.behavioral + sum.byRank.boss.behavioral === IMPLEMENTED.length,
      `impl=${IMPLEMENTED.length}`),
    raw('64 coverage: every implemented row resolves a non-empty behavior',
      rows.filter(r => r.behavioral).every(r => (enemyBehavior(r.key!)?.abilities.length ?? 0) > 0),
      rows.filter(r => r.behavioral).map(r => r.key).join(',')),
    raw('64 coverage: fallback rows resolve no behavior (default attack only)',
      rows.filter(r => !r.behavioral).every(r => r.key === null),
      `${rows.filter(r => !r.behavioral).length} fallback`),
  ]
  return cases
}
